/** The table the detector reads: which scripts name a language on their own,
 *  and the function words that separate languages sharing an alphabet. Data,
 *  never logic.
 *  NOT here: how the table is used, or any threshold
 *  (`pipeline/detect-language.ts`).
 *  Called by: `pipeline/detect-language.ts`. */

/**
 * Two mechanisms. `SCRIPT_PROFILES`: a script that names a language alone; such languages have no function words a
 * split on alphabetic boundaries could separate. `FUNCTION_WORDS`: Latin and Cyrillic scripts, where languages share
 * an alphabet; the score is the share of the sample's tokens found in a language's set.
 *
 * The sets overlap on purpose. Each holds the most frequent words of its own language even when another shares them:
 * a word left out of one language and listed by a rival gives the point to the rival. The score is relative, so the
 * overlap cancels out and the margin decides.
 *
 * Written limit: close languages block each other (Danish, Norwegian and Swedish first, then Spanish and Portuguese,
 * Czech and Polish, Russian and Ukrainian). The margin rule turns that into an abstention, so such a document may
 * never be translated, and is never translated wrongly. Their truly distinguishing words are listed to give the
 * margin a chance.
 *
 * The sets are hand-written, not derived from a corpus. A language missing from the table is never detected.
 */

/** Scripts that name a language alone. The order matters: Japanese mixes kana and han, so the kana test comes before
 *  the han test. */
export const SCRIPT_PROFILES: readonly { lang: string; pattern: RegExp }[] = [
  // Hiragana (U+3040-309F) and katakana (U+30A0-30FF).
  { lang: "ja", pattern: /[぀-ヿ]/gu },
  // Hangul: precomposed syllables (U+AC00-D7AF) and jamo (U+1100-11FF).
  { lang: "ko", pattern: /[가-힯ᄀ-ᇿ]/gu },
  // Han ideograms, reached only when neither kana nor hangul decided.
  { lang: "zh", pattern: /[一-鿿㐀-䶿]/gu },
  { lang: "el", pattern: /[Ͱ-Ͽἀ-῿]/gu },
  { lang: "he", pattern: /[֐-׿]/gu },
  { lang: "ar", pattern: /[؀-ۿݐ-ݿ]/gu },
];

